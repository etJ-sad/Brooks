"""Convert a monospace BDF font (ASCII 0x20..0x7E plus a few extras) into a C++ header.

Usage: bdf2c.py <font.bdf> <symbol> > out.h
Glyphs are stored row-major, each row padded to whole bytes, MSB = leftmost pixel.
"""
import sys

def main():
    path, sym = sys.argv[1], sys.argv[2]
    w = h = None
    glyphs = {}
    enc = None
    rows = None
    with open(path, encoding="latin-1") as f:
        for line in f:
            p = line.split()
            if not p:
                continue
            if p[0] == "FONTBOUNDINGBOX":
                w, h = int(p[1]), int(p[2])
            elif p[0] == "ENCODING":
                enc = int(p[1])
            elif p[0] == "BITMAP":
                rows = []
            elif p[0] == "ENDCHAR":
                if enc is not None and 0 <= enc < 256:
                    glyphs[enc] = rows
                rows = None
                enc = None
            elif rows is not None:
                rows.append(p[0])
    bpr = (w + 7) // 8
    out = []
    out.append("// Generated by tools/bdf2c.py from %s. Font license: see LICENSES/Spleen-BSD-2-Clause.txt" % path.split("/")[-1])
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    out.append("namespace font {")
    out.append("inline constexpr int %s_w = %d, %s_h = %d, %s_bpr = %d;" % (sym, w, sym, h, sym, bpr))
    out.append("inline constexpr uint8_t %s_data[256][%d] = {" % (sym, bpr * h))
    for c in range(256):
        r = glyphs.get(c) or glyphs.get(ord("?"))
        bs = []
        for row in r[:h]:
            bs.extend(bytes.fromhex(row.ljust(bpr * 2, "0")[: bpr * 2]))
        bs += [0] * (bpr * h - len(bs))
        out.append("  {" + ",".join("0x%02x" % b for b in bs) + "},")
    out.append("};")
    out.append("}  // namespace font")
    print("\n".join(out))

if __name__ == "__main__":
    main()
