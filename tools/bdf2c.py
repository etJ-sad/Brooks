"""Convert a monospace BDF font into a C++ header for the kernel console.

Usage: bdf2c.py <font.bdf> <symbol> > out.h

Only a subset of Unicode is kept (ASCII, Latin-1, Cyrillic, box drawing,
block elements, a few arrows and symbols). The header contains:
  <sym>_cp[]     sorted code points
  <sym>_data[][] glyph bitmaps, row-major, rows padded to bytes, MSB = leftmost
Glyph 0 is always '?', used for missing characters.
"""
import sys

RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x400, 0x45F), (0x2190, 0x2199), (0x2500, 0x259F),
          (0x25A0, 0x25FF), (0x2022, 0x2022), (0x2026, 0x2026), (0x2116, 0x2116)]

def wanted(c):
    return any(a <= c <= b for a, b in RANGES)

def main():
    path, sym = sys.argv[1], sys.argv[2]
    w = h = None
    glyphs = {}
    enc = None
    rows = None
    with open(path, encoding="latin-1") as f:
        for line in f:
            p = line.split()
            if not p:
                continue
            if p[0] == "FONTBOUNDINGBOX":
                w, h = int(p[1]), int(p[2])
            elif p[0] == "ENCODING":
                enc = int(p[1])
            elif p[0] == "BITMAP":
                rows = []
            elif p[0] == "ENDCHAR":
                if enc is not None and wanted(enc):
                    glyphs[enc] = rows
                rows = None
                enc = None
            elif rows is not None:
                rows.append(p[0])
    bpr = (w + 7) // 8
    cps = [ord("?")] + sorted(c for c in glyphs if c != ord("?"))
    out = []
    out.append("// Generated by tools/bdf2c.py from %s. Font license: LICENSES/Spleen-BSD-2-Clause.txt" % path.split("/")[-1])
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    out.append("namespace font {")
    out.append("inline constexpr int %s_w = %d, %s_h = %d, %s_bpr = %d, %s_count = %d;" % (sym, w, sym, h, sym, bpr, sym, len(cps)))
    out.append("// Code points; index 0 is the fallback glyph, the rest are sorted ascending.")
    out.append("inline constexpr uint16_t %s_cp[%d] = {" % (sym, len(cps)))
    for i in range(0, len(cps), 16):
        out.append("  " + ",".join("0x%04x" % c for c in cps[i:i + 16]) + ",")
    out.append("};")
    out.append("inline constexpr uint8_t %s_data[%d][%d] = {" % (sym, len(cps), bpr * h))
    for c in cps:
        bs = []
        for row in glyphs[c][:h]:
            bs.extend(bytes.fromhex(row.ljust(bpr * 2, "0")[: bpr * 2]))
        bs += [0] * (bpr * h - len(bs))
        out.append("  {" + ",".join("0x%02x" % b for b in bs) + "},")
    out.append("};")
    out.append("}  // namespace font")
    print("\n".join(out))

if __name__ == "__main__":
    main()
